// Embeds the extracted site drawing and model into assets/js/site-data.js so
// compositions can mount the site without any render-time fetch.
// Run: node scripts/build-site-data.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const svg = fs.readFileSync(path.join(root, 'assets/site/site-precise.svg'), 'utf8');
const model = JSON.parse(fs.readFileSync(path.join(root, 'assets/site/site-model.json'), 'utf8'));
const glyphs = fs.readFileSync(path.join(root, 'assets/site/glyphs.svg'), 'utf8');

const out = [
  '// GENERATED by scripts/build-site-data.mjs from assets/site/. Do not edit by hand.',
  `window.SITE_SVG = ${JSON.stringify(svg)};`,
  `window.SITE_MODEL = ${JSON.stringify(model)};`,
  `window.SITE_GLYPHS = ${JSON.stringify(glyphs)};`,
  '',
].join('\n');
fs.writeFileSync(path.join(root, 'assets/js/site-data.js'), out);
console.log(`site-data.js written (${(out.length / 1024).toFixed(0)} KB)`);

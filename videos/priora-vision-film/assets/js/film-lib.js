  FL.sortByDistance = function (els, p) {
    return [].concat(els)
      .map(function (el) {
        var b;
        try {
          b = el.getBBox();
        } catch (e) {
          b = { x: 0, y: 0, width: 0, height: 0 };
        }
        var dx = b.x + b.width / 2 - p[0],
          dy = b.y + b.height / 2 - p[1];
        return { el: el, d: dx * dx + dy * dy };
      })
      .sort(function (a, b) {
        return a.d - b.d;
      })
      .map(function (o) {
        return o.el;
      });
  };

  // Path tokeniser shared by jitterPath and normalizePath. Absolute and relative commands.
  var ARGS = { M: 2, L: 2, H: 1, V: 1, C: 6, S: 4, Q: 4, T: 2, A: 7, Z: 0 };
  function tokenize(d) {
    var out = [],
      re = /([MLHVCSQTAZmlhvcsqtaz])|(-?(?:\d+\.?\d*|\.\d+)(?:e[-+]?\d+)?)/g,
      m,
      cmd = null,
      buf = [];
    function flush() {
      if (cmd == null) return;
      var U = cmd.toUpperCase(),
        n = ARGS[U];
      if (n === 0) {
        out.push({ c: cmd, a: [] });
      } else {
        if (buf.length === 0 || buf.length % n !== 0) throw new Error("FL path: bad argument count for " + cmd);
        for (var i = 0; i < buf.length; i += n) out.push({ c: i === 0 ? cmd : cmd === "M" ? "L" : cmd === "m" ? "l" : cmd, a: buf.slice(i, i + n) });
      }
      buf = [];
    }
    while ((m = re.exec(d))) {
      if (m[1]) {
        flush();
        cmd = m[1];
        if (cmd === "Z" || cmd === "z") {
          flush();
          cmd = null;
        }
      } else buf.push(parseFloat(m[2]));
    }
    flush();
    return out;
  }
  function fmt(v) {
    var s = (Math.round(v * 1000) / 1000).toFixed(3);
    return s === "-0.000" ? "0.000" : s;
  }
  function serialize(segs) {
    return segs
      .map(function (s) {
        var arc = s.c === "A" || s.c === "a";
        return (
          s.c +
          s.a
            .map(function (v, i) {
              // arc flags (large-arc, sweep) must stay the integers 0 or 1
              return arc && (i === 3 || i === 4) ? (v ? "1" : "0") : fmt(v);
            })
            .join(" ")
        );
      })
      .join("");
  }
  FL.normalizePath = function (d) {
    return serialize(tokenize(d));
  };
  FL.jitterPath = function (d, rng, amount) {
    var segs = tokenize(d);
    segs.forEach(function (s) {
      var U = s.c.toUpperCase(),
        a = s.a;
      var j = function () {
        return (rng() * 2 - 1) * amount;
      };
      if (U === "A") {
        a[5] += j();
        a[6] += j();
      } else if (U === "H" || U === "V") {
        a[0] += j();
      } else {
        for (var i = 0; i < a.length; i++) a[i] += j();
      }
    });
    return serialize(segs);
  };

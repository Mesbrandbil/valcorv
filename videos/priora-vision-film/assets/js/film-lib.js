  function drawTween(tl, els, o, dir) {
    els = [].concat(els);
    var from = o.from == null ? 0 : o.from,
      to = o.to == null ? 1 : o.to;
    if (dir < 0) {
      var tmp = from;
      from = to;
      to = tmp;
    }
    // drawOn renders its start state at build time by default (lines hidden until drawn);
    // drawOff and any later tween on the same paths must not (it would overwrite that state).
    var ir = o.immediateRender != null ? !!o.immediateRender : dir > 0;
    var vars = { duration: o.duration == null ? 0.8 : o.duration, ease: o.ease || "power2.out", stagger: o.stagger || 0, immediateRender: ir };
    if (hasDrawSVG()) {
      var pct = function (f) {
        return "0% " + (f * 100).toFixed(3) + "%";
      };
      vars.drawSVG = pct(to);
      tl.fromTo(els, { drawSVG: pct(from) }, vars, o.at || 0);
    } else {
      els.forEach(function (el) {
        if (!el.__flLen) FL.prepDraw(el);
      });
      vars.strokeDashoffset = function (i, el) {
        return el.__flLen * (1 - to);
      };
      tl.fromTo(
        els,
        {
          strokeDashoffset: function (i, el) {
            return el.__flLen * (1 - from);
          },
        },
        vars,
        o.at || 0,
      );
    }
    return tl;
  }
